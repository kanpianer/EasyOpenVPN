#!/usr/bin/env bash
set -euo pipefail

# One-time privileged setup for SimpleOpenVPN's passwordless connect/disconnect.
#
# It installs a root-owned copy of the plugin's control script under
# /usr/local/lib/simpleopenvpn and a narrow polkit rule that authorizes only
# that exact program (and only connect/disconnect inside it). The desktop user
# still gets a confirmation card in the panel; the system password prompt is
# what disappears.
#
# Run from a terminal:
#   sudo ./setup-passwordless.sh
# Remove:
#   sudo ./setup-passwordless.sh --remove

target_user=""
remove=0

while (($# > 0)); do
  case "$1" in
    --remove)
      remove=1
      shift
      ;;
    --user)
      target_user=${2:?Usage: --user <name>}
      shift 2
      ;;
    -h|--help)
      sed -n '4,15p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *)
      echo "Unknown argument: $1" >&2
      exit 1
      ;;
  esac
done

if [[ ${EUID} -ne 0 ]]; then
  echo "This setup must run as root. Run it from a terminal with:" >&2
  echo "  sudo $0" >&2
  exit 1
fi

install_dir="/usr/local/lib/simpleopenvpn"
rule_file="/etc/polkit-1/rules.d/60-simpleopenvpn.rules"
source_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)

# Check every destination ancestor before root writes/removes anything. Never
# repair/chown an attacker-owned directory into apparent trust: reject it.
/usr/bin/python3 -I -S - "$install_dir" "$rule_file" <<'PY'
import os
import stat
import sys

for target in sys.argv[1:]:
    current = "/"
    for part in target.strip("/").split("/"):
        current = os.path.join(current, part)
        try:
            info = os.lstat(current)
        except FileNotFoundError:
            break
        if (stat.S_ISLNK(info.st_mode) or info.st_uid != 0
                or info.st_mode & 0o022):
            raise SystemExit(f"EasyOpenVPN: unsafe installation path: {current}")
        if current != target and not stat.S_ISDIR(info.st_mode):
            raise SystemExit(f"EasyOpenVPN: not a directory: {current}")
# Existing leaves must also be trusted; in particular never truncate an ABI
# symlink or write through a hard link to an unrelated privileged file.
for name in ("openvpn-ctl", "openvpn-lib", "abi"):
    path = os.path.join(sys.argv[1], name)
    try:
        info = os.lstat(path)
    except FileNotFoundError:
        continue
    if (not stat.S_ISREG(info.st_mode) or info.st_uid != 0
            or info.st_mode & 0o022 or info.st_nlink != 1):
        raise SystemExit(f"EasyOpenVPN: unsafe installed file: {path}")
PY

if ((remove)); then
  rm -f -- "$rule_file"
  rm -rf -- "$install_dir"
  systemctl try-reload-or-restart polkit.service 2>/dev/null || true
  echo "SimpleOpenVPN passwordless setup removed."
  exit 0
fi

if [[ -z "$target_user" && -n "${SUDO_USER:-}" ]]; then
  target_user=$SUDO_USER
fi
if [[ -z "$target_user" && -n "${PKEXEC_UID:-}" ]]; then
  target_user=$(getent passwd "$PKEXEC_UID" 2>/dev/null | cut -d: -f1 || true)
fi
if [[ -z "$target_user" || "$target_user" == "root" ]]; then
  echo "Could not determine the desktop user." >&2
  echo "Run this with sudo from your desktop account, or pass --user <name>." >&2
  exit 1
fi
if [[ ! "$target_user" =~ ^[A-Za-z0-9._-]+$ ]]; then
  echo "Unsupported user name: $target_user" >&2
  exit 1
fi

for file in openvpn-ctl openvpn-lib; do
  if [[ ! -f "$source_dir/scripts/$file" ]]; then
    echo "Missing $source_dir/scripts/$file" >&2
    exit 1
  fi
done

if [[ ! -d /etc/polkit-1/rules.d ]]; then
  echo "Missing /etc/polkit-1/rules.d; is polkit installed?" >&2
  exit 1
fi

install -d -o root -g root -m 0755 "$install_dir"
install -o root -g root -m 0755 "$source_dir/scripts/openvpn-ctl" "$install_dir/openvpn-ctl"
install -o root -g root -m 0644 "$source_dir/scripts/openvpn-lib" "$install_dir/openvpn-lib"

# ABI marker checked by openvpn_passwordless_available(). Keep it in sync with
# openvpn_helper_abi in openvpn-lib.
# ABI 4: includes guard/log integrity and nonblocking privileged reads.
printf '4\n' > "$install_dir/abi"
chown root:root "$install_dir/abi"
chmod 0644 "$install_dir/abi"

tmp_rule=$(mktemp)
trap 'rm -f -- "$tmp_rule"' EXIT
cat > "$tmp_rule" <<EOF
// Generated by SimpleOpenVPN setup-passwordless.sh. Do not edit by hand.
polkit.addRule(function(action, subject) {
    if (action.id == "org.freedesktop.policykit.exec" &&
        action.lookup("program") == "$install_dir/openvpn-ctl" &&
        subject.user == "$target_user") {
        // Defence-in-depth: when the polkit version exposes the full command
        // line, restrict to the two subcommands the rule is intended to cover.
        // Older polkit versions that do not populate command_line return an
        // empty string; in that case the program-path check above is sufficient.
        var cmdline = action.lookup("command_line") || "";
        if (cmdline !== "" &&
            cmdline !== "$install_dir/openvpn-ctl connect" &&
            cmdline !== "$install_dir/openvpn-ctl disconnect") {
            return polkit.Result.NOT_HANDLED;
        }
        return polkit.Result.YES;
    }
});
EOF
install -o root -g root -m 0644 "$tmp_rule" "$rule_file"
rm -f -- "$tmp_rule"
trap - EXIT

systemctl try-reload-or-restart polkit.service 2>/dev/null || true

# Never write UI bookkeeping inside the desktop user's home as root. The
# unprivileged setup_passwordless action records the prompt before pkexec;
# user-controlled parent directories or symlinks must not redirect root writes.

cat <<EOF
Passwordless SimpleOpenVPN connect is now enabled for user: $target_user

Installed:
  $install_dir/openvpn-ctl
  $install_dir/openvpn-lib
  $rule_file

The panel still shows a confirmation card before connecting; the system
password prompt is gone. Re-run this script after updating the plugin so the
installed copy matches. Remove with: sudo $0 --remove

IMPORTANT: If you had a previous (ABI 1, 2 or 3) installation, the old helper has been
replaced. The plugin will now delegate to the updated helper automatically.
EOF
